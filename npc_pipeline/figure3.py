def plot_calibration_panel(ax, cohort, panel_label):
    bins_sub = cal_bins[(cal_bins['cohort'] == cohort) & (cal_bins['model'] == 'M3')].copy()
    met = cal_metrics[(cal_metrics['cohort'] == cohort) & (cal_metrics['model'] == 'M3')].iloc[0]
    ax.plot([0, 1], [0, 1], linestyle='--', color=CAL_IDEAL_COLOR, linewidth=1.0, label='Ideal')
    yerr = np.vstack([bins_sub['observed_fraction'] - bins_sub['observed_ci_low'], bins_sub['observed_ci_high'] - bins_sub['observed_fraction']])
    ax.plot(bins_sub['mean_predicted'], bins_sub['observed_fraction'], color=CAL_OBS_COLOR, linewidth=0.95, marker='o', markersize=4.2, label='Observed')
    ax.errorbar(bins_sub['mean_predicted'], bins_sub['observed_fraction'], yerr=yerr, fmt='none', ecolor=CAL_OBS_COLOR, elinewidth=0.7, capsize=2.0, alpha=0.7)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_xlabel('Predicted probability')
    ax.set_ylabel('Observed event probability')
    ax.set_title('Development cohort' if cohort == 'Development' else 'Independent external validation cohort')
    ax.grid(alpha=0.18, linewidth=0.5)
    txt = f"Brier score = {met['brier_score']:.3f}\nCalibration-in-the-large = {met['calibration_in_the_large']:.2f}\nCalibration slope = {met['calibration_slope']:.2f}"
    ax.text(0.04, 0.96, txt, transform=ax.transAxes, ha='left', va='top', fontsize=7.3)
    ax.text(-0.13, 1.05, panel_label, transform=ax.transAxes, fontsize=10.5, fontweight='bold', va='top')
    ax.legend(loc='lower right', frameon=False)
